"""Production vendor-override audit record (HDE-CLI-API-Vendor-Ref §7.1.11e–f).

One append-only, locally durable, keys-only JSONL event per production-like
``bg:resolve --source vendor`` invocation that reaches override evaluation.
The actor, the sink, the clock and the correlation ID are module-level seams
so tests can replace them; nothing here reads the subject, the configured URL,
any header or key value, or raw provider data.
"""

from __future__ import annotations

import os
import stat
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Mapping

from engine.serializer.canon import sercanon

VENDOR_PROD_OVERRIDE_AUDIT_SCHEMA_VERSION = "vendor_prod_override.v1"
VENDOR_PROD_OVERRIDE_EVENT = "vendor_prod_override"
VENDOR_OVERRIDE_AUDIT_PATH_KEY = "HDE_VENDOR_OVERRIDE_AUDIT_PATH"
DEFAULT_AUDIT_SUBPATH = Path("glow-hdengine") / "vendor_prod_override.jsonl"
AUDIT_OUTCOMES = frozenset({"refused", "allowed", "failed", "completed"})
AUDIT_FIELDS = (
    "actor_principal",
    "authorization_ref",
    "command",
    "correlation_id",
    "environment",
    "error_code",
    "event",
    "network_open",
    "occurred_at",
    "outbound_attempted",
    "outcome",
    "resource_path",
    "route_family",
    "safe_mode_open",
    "schema_version",
    "source",
)

_REPOSITORY_ROOT = Path(__file__).resolve().parents[2]


class AuditUnavailable(Exception):
    """The actor or the sink is unavailable; the reason is never surfaced."""


def utc_now() -> datetime:
    """Clock seam: the current UTC time."""

    return datetime.now(timezone.utc)


def new_correlation_id() -> str:
    """Correlation seam: generated by the runtime, never taken from input."""

    return str(uuid.uuid4())


def resolve_actor_principal() -> str:
    """Actor seam: the account name of the process's effective user ID.

    Read from the system user database through the process's own credentials,
    never from ``USER``, ``LOGNAME``, ``LNAME``, ``USERNAME`` or any other
    caller-settable value. A UID without an account name is not a stable
    authenticated identity.
    """

    try:
        import pwd

        name = pwd.getpwuid(os.geteuid()).pw_name
    except (ImportError, AttributeError, KeyError, OSError):
        raise AuditUnavailable() from None
    principal = sanitize_field(name)
    if not principal:
        raise AuditUnavailable()
    return principal


def resolve_sink_path(env: Mapping[str, object]) -> Path:
    """Sink seam: the operator key, else the operator's state directory."""

    configured = env.get(VENDOR_OVERRIDE_AUDIT_PATH_KEY)
    if isinstance(configured, str) and configured.strip():
        candidate = Path(configured.strip())
    else:
        state_home = env.get("XDG_STATE_HOME")
        if isinstance(state_home, str) and state_home.strip() and Path(state_home.strip()).is_absolute():
            base = Path(state_home.strip())
        else:
            home = os.path.expanduser("~")
            if home == "~" or not Path(home).is_absolute():
                raise AuditUnavailable()
            base = Path(home) / ".local" / "state"
        candidate = base / DEFAULT_AUDIT_SUBPATH
    if not candidate.is_absolute():
        raise AuditUnavailable()
    resolved = Path(os.path.realpath(candidate))
    if resolved == _REPOSITORY_ROOT or _REPOSITORY_ROOT in resolved.parents:
        raise AuditUnavailable()
    return resolved


def sanitize_field(value: str) -> str:
    """Keep printable ASCII only, so no CR, LF, control or delimiter byte survives."""

    return "".join(ch if " " <= ch <= "~" else "?" for ch in value)


def build_event(
    *,
    correlation_id: str,
    actor_principal: str,
    authorization_ref: str | None,
    environment: str,
    outcome: str,
    error_code: str | None,
    outbound_attempted: bool,
    route_family: str | None = None,
    resource_path: str | None = None,
) -> dict[str, Any]:
    if outcome not in AUDIT_OUTCOMES:
        raise ValueError("unsupported audit outcome")

    def _optional(value: str | None) -> str | None:
        return None if value is None else sanitize_field(str(value))

    return {
        "schema_version": VENDOR_PROD_OVERRIDE_AUDIT_SCHEMA_VERSION,
        "event": VENDOR_PROD_OVERRIDE_EVENT,
        "occurred_at": utc_now().astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%fZ"),
        "correlation_id": sanitize_field(correlation_id),
        "actor_principal": sanitize_field(actor_principal),
        "authorization_ref": _optional(authorization_ref),
        "command": "bg:resolve",
        "source": "vendor",
        "environment": sanitize_field(environment),
        "safe_mode_open": True,
        "network_open": True,
        "route_family": _optional(route_family),
        "resource_path": _optional(resource_path),
        "outcome": outcome,
        "error_code": _optional(error_code),
        "outbound_attempted": bool(outbound_attempted),
    }


def append_event(sink: Path, event: Mapping[str, Any]) -> None:
    """Append one canonical JSON line, then flush and fsync it.

    A missing parent directory is created owner-only. The file is created
    owner-only, opened for append, and must be a regular file. After the file,
    the directory holding it and the parent of every directory created here
    are fsynced, so the entries survive a crash as well as the line does. Any
    failure is :class:`AuditUnavailable`.
    """

    line = sercanon(dict(event))
    try:
        created: list[Path] = []
        directory = sink.parent
        while not directory.exists():
            created.append(directory)
            directory = directory.parent
        sink.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
        fd = os.open(sink, os.O_WRONLY | os.O_APPEND | os.O_CREAT | getattr(os, "O_CLOEXEC", 0), 0o600)
    except OSError:
        raise AuditUnavailable() from None
    try:
        if not stat.S_ISREG(os.fstat(fd).st_mode):
            raise AuditUnavailable()
        view = memoryview(line)
        while view:
            written = os.write(fd, view)
            view = view[written:]
        os.fsync(fd)
    except OSError:
        raise AuditUnavailable() from None
    finally:
        os.close(fd)
    # fsync on the file does not persist its directory entry (§7.1.11f: durable before I/O).
    for entry_holder in (sink.parent, *(path.parent for path in created)):
        _fsync_directory(entry_holder)


def _fsync_directory(directory: Path) -> None:
    try:
        fd = os.open(directory, os.O_RDONLY | getattr(os, "O_DIRECTORY", 0) | getattr(os, "O_CLOEXEC", 0))
    except OSError:
        raise AuditUnavailable() from None
    try:
        os.fsync(fd)
    except OSError:
        raise AuditUnavailable() from None
    finally:
        os.close(fd)
