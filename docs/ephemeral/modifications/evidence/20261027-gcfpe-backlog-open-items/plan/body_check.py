# --- the operation set for one page --------------------------------------------------------------------------
def static_ops(prompt: str, conditional: list) -> list:
    ops = [o for o in EDITS["ops"] if o["prompt"] == prompt]
    for c in EDITS.get("conditional_ops", []):
        if c["set"] in conditional:
            ops += [o for o in c["ops"] if o["prompt"] == prompt]
    return ops


def page_ops(prompt: str, body: str, smap: dict, conditional: list, shared: dict) -> tuple[list, dict]:
    """Static operations with their replacements binding-rewritten, then the generated binding operations. Returns
    (ops, info); under a stand-in map, binding ops whose replacement expands to their old text are left out and
    counted."""
    ops, rewritten = [], 0
    for o in static_ops(prompt, conditional):
        if o.get("head"):
            ops.append(o)
            continue
        new, n = bp.rewrite_replacement(o["new"], smap)
        if n:
            rewritten += 1
            ops.append(dict(o, new=new, binding_rewritten=n))
        else:
            ops.append(o)
    covered = []
    for o in ops:
        span, _ = resolve(body, o)
        if span is not None:
            covered.append(span)
    gen = bp.generate(body, prompt, smap, covered)
    identity = 0
    for b in gen["ops"]:
        if expand(b["new"], shared) == b["start"]:
            identity += 1
            continue
        ops.append(b)
    info = {"binding_ops": len(gen["ops"]) - identity, "binding_identity_under_stand_in": identity,
            "binding_stale_lines": gen["stale_lines"], "binding_skipped_covered": gen["skipped_covered"],
            "binding_partial_line_ops": gen["partial_line_ops"], "binding_unresolved": gen["unresolved"],
            "binding_unresolved_lines": gen["unresolved_line_numbers"],
            "worker_replacements_binding_rewritten": rewritten}
    return ops, info


