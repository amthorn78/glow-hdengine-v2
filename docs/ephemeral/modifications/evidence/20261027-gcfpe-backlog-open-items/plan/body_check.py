def _registry_pass(evaluate, g: dict, text: str) -> bool:
    """C-15: the registry form runs on the normalized text, as the guard does."""
    (k, v), = to_registry(g).items()
    return not evaluate({"prompt_key": g["id"], "audit_assertions": {k: [v]}}, nf.normalize(text), "transient")


def registry(audit_root: str, root: str, session: str, since: int, fetched_after: str, conditional: list) -> dict:
    evaluate = _engine(audit_root)
    guards = active_guards(STATE["map"])
    fixtures, pages, ok = [], [], True
    for g in guards:
        if g.get("surface", "prompt-body") != "prompt-body" or g.get("regenerate"):
            continue
        for want, fxs in (("pass", g["fixtures"]["pass"]), ("fail", g["fixtures"]["fail"])):
            for k, fx in enumerate(fxs):
                text = expand(fx)
                agree = _registry_pass(evaluate, g, text) == guard_pass(text, g)[1] == (want == "pass")
                ok &= agree
                fixtures.append({"guard": g["id"], "fixture": f"{want}[{k}]", "agrees": agree})
        for k, fx in enumerate(g["fixtures"].get("fail_count_only", [])):
            text = expand(fx)
            agree = _registry_pass(evaluate, g, text) and not guard_pass(text, g)[1]
            ok &= agree
            fixtures.append({"guard": g["id"], "fixture": f"fail_count_only[{k}]", "agrees": agree})
    for prompt, meta in EDITS["pages"].items():
        got = latest_fetch(meta["page_id"], root, session, since, fetched_after)
        if got is None:
            pages.append({"prompt": prompt, "error": "NO_FETCH_FOUND"})
            ok = False
            continue
        before = got[2]
        ops, _ = page_ops(prompt, before, STATE["map"], conditional, SHARED)
        after, _ = apply_all(before, ops)
        for g in guards_for(prompt, guards):
            row = {"prompt": prompt, "guard": g["id"]}
            for label, text in (("before", before), ("after", after)):
                reg, grd = _registry_pass(evaluate, g, text), guard_pass(text, g)[1]
                row[f"{label}_registry_pass"], row[f"{label}_guard_pass"] = reg, grd
            row["agrees"] = (row["before_registry_pass"] == row["before_guard_pass"]
                             and row["after_registry_pass"] == row["after_guard_pass"] and row["after_guard_pass"])
            ok &= row["agrees"]
            pages.append(row)
    return {"mode": "registry", "stand_in": STATE["stand_in"], "fixture_rows": len(fixtures),
            "fixtures_disagreeing": [f for f in fixtures if not f["agrees"]],
            "page_rows": len(pages), "pages_disagreeing": [p for p in pages if not p.get("agrees")], "ok": ok,
            "d22": "transient reads of this session's harness records; no body text in this report"}


