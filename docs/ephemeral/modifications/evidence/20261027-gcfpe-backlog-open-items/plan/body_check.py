def run(mode: str, prompts, no_ops: bool, root: str, session: str, since: int, fetched_after: str,
        conditional: list) -> dict:
    smap = STATE["map"]
    guards = active_guards(smap)
    probe_map = bp.probe(smap) if STATE["stand_in"] else None
    pshared = dict(SHARED, **bp.shared_from_map(probe_map)) if probe_map else None
    pguards = active_guards(probe_map) if probe_map else None
    out, ops_payload, all_ok = [], [], True
    for prompt, meta in EDITS["pages"].items():
        if prompts and prompt not in prompts:
            continue
        fetches = all_fetches(meta["page_id"], root, session, since, fetched_after)
        if not fetches:
            out.append({"prompt": prompt, "error": "NO_FETCH_FOUND"})
            all_ok = False
            continue
        captured, as_of, body = fetches[-1]
        row = {"prompt": prompt, "fetch_captured": captured, "as_of": as_of}
        try:
            ops, info = page_ops(prompt, body, smap, conditional, SHARED)
        except Unfilled as e:
            out.append({"prompt": prompt, "error": f"UNFILLED_TOKEN {e}"})
            all_ok = False
            continue
        row.update(info)
        row["ops_by_source"] = {}
        for o in ops:
            row["ops_by_source"][o["source"]] = row["ops_by_source"].get(o["source"], 0) + 1
        if mode == "plan":
            row["revision_matches_plan"] = bool(meta["expected_last_edited"]) and as_of == meta["expected_last_edited"]
            row["guards_before"] = {g["id"]: dict(zip(("count", "pass"), guard_pass(body, g)))
                                    for g in guards_for(prompt, guards)}
            text, op_rows = apply_all(body, ops)
            for r, o in zip(op_rows, ops):   # AM-1
                if not r["applied"] and satisfied_by_duplication(body, o, meta["page_id"]):
                    r["satisfied_by_duplication"] = True
            row["batch_safe"] = batch_rows(body, text, op_rows, ops, smap)
            for r in op_rows:
                if r["applied"] and not no_ops:
                    ops_payload.append({"id": r["id"], "page_id": meta["page_id"], "old_str": r["old_str"],
                                        "new_str": r["new_str"]})
            row["ops"] = [{k: v for k, v in r.items() if k not in ("old_str", "new_str")} for r in op_rows]
            row["ops_not_applied"] = [r["id"] for r in op_rows if not r["applied"]
                                      and not r.get("satisfied_by_duplication")]
            row["ops_satisfied_by_duplication"] = [r["id"] for r in op_rows if r.get("satisfied_by_duplication")]
            row["markup_spans_allowed"] = sum(1 for r in op_rows if r.get("span_has_markup"))
            row["markup_spans_refused"] = [r["id"] for r in op_rows if r.get("span_has_markup")
                                           and not r.get("markup_allowed")]
            row["refs_dropped"] = [r["id"] for r in op_rows if r.get("refs_kept") is False]
            row["guards_after"] = {g["id"]: dict(zip(("count", "pass"), guard_pass(text, g)))
                                   for g in guards_for(prompt, guards)}
            row["guards_failing_after"] = [k for k, v in row["guards_after"].items() if not v["pass"]]
            row["landed_state_after"] = {o["id"]: state(text, o) for o in ops}
            row["end_anchor_not_unique"] = [r["id"] for r in op_rows if r.get("end_unique_in_original") is False]
            row["check_would_pass"] = all(landed(text, o, ops)["landed"] for o in ops)
            regen = bp.generate(text, prompt, smap, covered=[])
            row["binding_current_after"] = (sum(1 for b in regen["ops"] if expand(b["new"]) != b["start"]) == 0
                                            and regen["unresolved"] == 0)
            row["ok"] = (row["revision_matches_plan"]
                         and all(r["applied"] or r.get("satisfied_by_duplication") for r in op_rows) and row["batch_safe"]
                         and not row["guards_failing_after"]
                         and all(v == "LANDED" for v in row["landed_state_after"].values())
                         and row["check_would_pass"] and info["binding_unresolved"] == 0
                         and row["binding_current_after"])
            if probe_map is not None:
                pops, pinfo = page_ops(prompt, body, probe_map, conditional, pshared)
                ptext, prows = apply_all(body, pops, pshared)
                pg = {g["id"]: g for g in pguards}
                row["probe"] = {"ops_applied": sum(1 for r in prows if r["applied"]), "ops": len(pops),
                                "batch_safe": batch_rows(body, ptext, prows, pops, probe_map, pshared),
                                "bind_after": guard_count(ptext, pg["G-W7-BIND-1"]),
                                "bind_before": guard_count(body, pg["G-W7-BIND-1"]),
                                "name_after": guard_count(ptext, pg["G-W8-NAME-1"]),
                                "name_before": guard_count(body, pg["G-W8-NAME-1"]),
                                "unresolved": pinfo["binding_unresolved"]}
                p = row["probe"]
                p["ok"] = (p["ops_applied"] == p["ops"] and p["batch_safe"] and p["bind_after"] == 0
                           and p["name_after"] == 0 and p["unresolved"] == 0)
                row["ok"] &= p["ok"]
        else:
            row["revision_moved"] = as_of != meta["expected_last_edited"]
            row["ops"] = {o["id"]: landed(body, o, ops) for o in ops if not o.get("binding")}
            regen = bp.generate(body, prompt, smap, covered=[])
            row["binding_current"] = len(regen["ops"]) == 0 and regen["unresolved"] == 0
            row["guards"] = {g["id"]: dict(zip(("count", "pass"), guard_pass(body, g)))
                             for g in guards_for(prompt, guards)}
            row["ok"] = (row["revision_moved"] and all(v["landed"] for v in row["ops"].values())
                         and row["binding_current"] and all(v["pass"] for v in row["guards"].values()))
        all_ok &= row["ok"]
        out.append(row)
    result = {"mode": mode, "stand_in": STATE["stand_in"], "conditional_sets": conditional, "pages": out,
              "pages_ok": sum(1 for r in out if r.get("ok")), "pages_total": len(out), "ok": all_ok,
              "d22": "transient reads of this session's harness records; no body text in this report"}
    if STATE["stand_in"]:
        result["stand_in_note"] = ("stand-in successor map: each successor page = its predecessor, CL-05 = the "
                                   "candidate; URL-only binding rewrites are identities (counted per page), and the "
                                   "probe pass with synthetic successor ids carries the URL half of the binding check")
    if mode == "plan" and not no_ops:
        result["ops_payload_for_execute"] = ops_payload
    return result


