class Unfilled(Exception):
    pass


def expand(text: str, shared: dict | None = None) -> str:
    shared = SHARED if shared is None else shared
    for _ in range(3):  # aliases (@CL05_URL -> @SUCC_URL_CL-05) expand on the next round
        before = text
        for key in sorted(shared, key=len, reverse=True):
            text = text.replace("@" + key, shared[key])
        if text == before:
            break
    if TOKEN_LEFT.search(text):
        raise Unfilled(TOKEN_LEFT.search(text).group(0))
    return text


def occ(text: str, s: str) -> int:
    n, i = 0, text.find(s)
    while i >= 0:
        n += 1
        i = text.find(s, i + 1)
    return n


# --- transient read of the newest fetch (D22), as in the precedent --------------------------------------------
def _texts(obj):
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k == "text" and isinstance(v, str):
                yield v
            else:
                yield from _texts(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from _texts(v)


def _recent_lines(path: str, cutoff_iso: str):
    with open(path, "rb") as fh:
        fh.seek(0, os.SEEK_END)
        pos, tail = fh.tell(), b""
        while pos > 0:
            step = min(1 << 20, pos)
            pos -= step
            fh.seek(pos)
            lines = (fh.read(step) + tail).split(b"\n")
            tail = lines.pop(0) if pos > 0 else b""
            for raw in reversed(lines):
                if not raw.strip():
                    continue
                try:
                    obj = json.loads(raw)
                except ValueError:
                    continue
                ts = obj.get("timestamp") if isinstance(obj, dict) else None
                if isinstance(ts, str) and ts < cutoff_iso:
                    return
                yield obj


def all_fetches(page_id: str, root: str, session: str, since_minutes: int, fetched_after: str = "") -> list:
    page = page_id.replace("-", "")
    cutoff = time.time() - since_minutes * 60
    if fetched_after:
        cutoff = max(cutoff, datetime.strptime(fetched_after, "%Y-%m-%dT%H:%M:%S.%fZ")
                     .replace(tzinfo=timezone.utc).timestamp())
    cutoff_iso = datetime.fromtimestamp(cutoff, timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"
    base = os.path.join(root, "*", session)
    files = glob.glob(base + ".jsonl") + glob.glob(base + "/tool-results/*") \
        + glob.glob(base + "/subagents/**/*.jsonl", recursive=True) \
        + glob.glob(base + "/subagents/**/tool-results/*", recursive=True)
    found = {}
    for f in files:
        if os.path.getmtime(f) < cutoff:
            continue
        if f.endswith(".jsonl"):
            entries = _recent_lines(f, cutoff_iso)
        else:
            try:
                raw = open(f, encoding="utf-8").read()
                entries = [json.loads(raw)] if page in raw else []
            except (OSError, ValueError):
                continue
        for obj in entries:
            ts = obj.get("timestamp") if isinstance(obj, dict) else None
            for t in _texts(obj):
                inner = t
                if not inner.startswith("Here is the result of"):
                    try:
                        inner = json.loads(t)["text"]
                    except (ValueError, KeyError, TypeError):
                        continue
                head = FETCH_HEAD.match(inner)
                if not head or head.group(1).replace("-", "") != page:
                    continue
                m = re.search(r"<content>\n?(.*)</content>", inner, re.S)
                if not m:
                    continue
                captured = ts if f.endswith(".jsonl") else datetime.fromtimestamp(
                    os.path.getmtime(f), timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f")[:-3] + "Z"
                if not captured or captured < cutoff_iso:
                    continue
                key = (head.group(2), m.group(1))
                if key not in found or captured > found[key][0]:
                    found[key] = (captured, head.group(2), m.group(1))
    return sorted(found.values(), key=lambda c: c[0])


def latest_fetch(page_id: str, root: str, session: str, since_minutes: int, fetched_after: str = ""):
    got = all_fetches(page_id, root, session, since_minutes, fetched_after)
    return got[-1] if got else None


# --- spans and operations -----------------------------------------------------------------------------------
def resolve(text: str, op: dict):
    s = op["start"]
    n = occ(text, s)
    if n != 1:
        return None, f"START_COUNT_{n}"
    i = text.find(s)
    if op.get("end") is None:
        return (i, i + len(s)), None
    j = text.find(op["end"], i + len(s))
    if op.get("lines") is not None:
        if j < 0 or occ(text[i + len(s):], op["end"]) != 1:
            return None, "END_NOT_UNIQUE_AFTER_START"
        if text[i:j + len(op["end"])].count("\n") != op["lines"]:
            return None, "SPAN_LINES_" + str(text[i:j + len(op["end"])].count("\n"))
        return (i, j + len(op["end"])), None
    line_end = text.find("\n", i)
    line_end = len(text) if line_end < 0 else line_end
    if j < 0 or j + len(op["end"]) > line_end:
        return None, "END_NOT_ON_LINE"
    return (i, j + len(op["end"])), None


def state(text: str, op: dict, shared=None) -> str:
    """UNTOUCHED: nothing has replaced the span yet. For an insertion (its replacement keeps the start anchor) that
    means the span resolves and the replacement is absent, as in the precedent; for a replacement or deletion it
    means the span resolves, since landing removes the start anchor. That second rule differs from the precedent,
    which also asked the replacement to be absent: it read CONFLICT for a replacement that is part of its own span
    (CL05-01 keeps its end heading, W6-PE-14e keeps its tail) or that another operation's replacement also writes
    (HP-DOC-20-02 and W1-DOC20-01 under C-5 Q-2). LANDED: the span is gone and the replacement present (any
    deletion: the start anchor gone). Anything else is CONFLICT, and nothing is applied to it."""
    span, _ = resolve(text, op)
    new = expand(op["new"], shared)
    if new and op["start"] in new:
        if span is not None and occ(text, new) == 0:
            return "UNTOUCHED"
        if occ(text, new) >= 1 and occ(text, op["start"]) == occ(text, new) * occ(new, op["start"]):
            return "LANDED"
        return "CONFLICT"
    if span is not None:
        return "UNTOUCHED"
    if occ(text, op["start"]) == 0 and (new == "" or occ(text, new) >= 1):
        return "LANDED"
    return "CONFLICT"


def landed(text: str, op: dict, page_ops: list, shared=None) -> dict:
    news = [expand(o["new"], shared) for o in page_ops]
    want = lambda s: sum(occ(n, s) for n in news)
    new = expand(op["new"], shared)
    row = {"start": occ(text, op["start"]) == want(op["start"])}
    if new:
        row["new"] = occ(text, new) == want(new) >= 1
    if op.get("end") is not None:
        row["end"] = occ(text, op["end"]) == want(op["end"])
    if new and op["start"] in new:
        i = new.find(op["start"])
        for key, part in (("inserted_before", new[:i].strip()), ("inserted_after", new[i + len(op["start"]):].strip())):
            if part:
                row[key] = occ(text, part) == want(part)
    row["landed"] = all(row.values())
    return row


PAGE_URL = "https://app.notion.com/p/"


def satisfied_by_duplication(text: str, op: dict, page_id: str, shared=None) -> bool:
    """AM-1: a head self-mention operation whose work the duplication already did (see the module docstring)."""
    if not (op.get("head") and "<mention url=" in op["start"]):
        return False
    new = expand(op["new"], shared)
    return (occ(text, op["start"]) == 0 and bool(new) and occ(text, new) == 1
            and (PAGE_URL + page_id.replace("-", "")) in new)


def markup(s: str) -> bool:
    return any(m in s for m in ("<", "](", "\\"))


def refs_kept(old: str, new: str, op: dict, smap: dict | None = None) -> bool:
    """Every page an allowed markup span names is still named by its replacement, at the successor where the map gives
    one; a worker op may drop a page only by listing it in drops_refs."""
    smap = smap or STATE["map"]
    succ = {p: s for _, p, _, s, _ in bp.successors(smap)} if smap else {}
    have = set(REF.findall(new))
    return all(succ.get(r, r) in have or r in have or r in op.get("drops_refs", []) for r in REF.findall(old))


def apply_all(text: str, ops: list, shared=None) -> tuple[str, list]:
    rows = []
    for o in ops:
        before = state(text, o, shared)
        span, why = resolve(text, o)
        applied = before == "UNTOUCHED" and span is not None
        old = text[span[0]:span[1]] if applied else None
        count_at_application = occ(text, old) if applied else None
        if applied:
            text = text[:span[0]] + expand(o["new"], shared) + text[span[1]:]
        rows.append({"id": o["id"], "state_before": before, "refusal": why, "applied": applied, "old_str": old,
                     "new_str": expand(o["new"], shared) if applied else None,
                     "old_str_count_at_application": count_at_application})
    return text, rows


def batch_rows(body: str, text: str, op_rows: list, ops: list, smap: dict | None = None, shared=None) -> bool:
    """One update_content call carries every operation of the page: each old_str must name its span alone in the
    unedited page, occur once at application, and be gone afterwards. A span carrying markup is refused unless its
    operation allows markup, and then it must keep its page references."""
    for r in op_rows:
        if r["applied"]:
            op = next(o for o in ops if o["id"] == r["id"])
            r["old_str_unique_in_original"] = occ(body, r["old_str"]) == 1
            r["end_unique_in_original"] = op.get("end") is None or occ(body, op["end"]) == 1
            r["old_str_once_at_application"] = r.pop("old_str_count_at_application") == 1
            r["old_str_only_in_own_new_after"] = (occ(text, r["old_str"]) == occ(r["new_str"], r["old_str"])
                                                  if r["new_str"] else occ(text, r["old_str"]) == 0)
            r["span_has_markup"] = markup(r["old_str"])
            r["markup_allowed"] = bool(op.get("allow_markup"))
            if r["span_has_markup"] and r["markup_allowed"]:
                r["refs_kept"] = refs_kept(r["old_str"], r["new_str"], op, smap)
            # The precedent required the end anchor to occur once in the unedited page, because the landing check
            # counts it. An end that also occurs elsewhere is safe when its count after the whole batch is the count
            # the page's replacements carry, which is the landing check's own end test; the row says which held.
            if not r["end_unique_in_original"]:
                news = [expand(o["new"], shared) for o in ops]
                r["end_count_matches_replacements_after"] = occ(text, op["end"]) == sum(occ(n, op["end"]) for n in news)
    return all(r.get("old_str_unique_in_original") and r.get("old_str_once_at_application")
               and r.get("old_str_only_in_own_new_after")
               and (r.get("end_unique_in_original") or r.get("end_count_matches_replacements_after"))
               and (not r.get("span_has_markup") or r.get("markup_allowed")) and r.get("refs_kept", True)
               for r in op_rows if r["applied"])


# --- guards -------------------------------------------------------------------------------------------------
def units(text: str, unit: str):
    for line in text.split("\n"):
        if unit == "line":
            yield line
        else:
            yield from (s for s in re.split(r"(?<=[.!?])\s+", line) if s)


def raw_guard_count(text: str, g: dict) -> int:
    """The unit count on the text exactly as given; only the self-test calls it, to show that normalization is what
    makes a pattern written for the Markdown form fire on a fetch-form read."""
    n = 0
    for u in units(text, g["unit"]):
        if all(re.search(p, u) for p in g["all"]) and not any(re.search(p, u) for p in g.get("except", [])):
            n += 1
    return n


def guard_count(text: str, g: dict) -> int:
    """C-15: every guard runs on the normalized (Markdown) form of the text it is given."""
    return raw_guard_count(nf.normalize(text), g)


def guard_pass(text: str, g: dict) -> tuple[int, bool]:
    c = guard_count(text, g)
    return c, (c == 0 if g["kind"] == "forbidden" else c == g["expect"])


