    ap.add_argument("--no-ops", action="store_true")
    ap.add_argument("--prompts", nargs="*")
    ap.add_argument("--since-minutes", type=int, default=60)
    ap.add_argument("--fetched-after", default="")
    ap.add_argument("--harness-root", default=os.path.expanduser("~/.claude/projects"))
    ap.add_argument("--session", default=os.environ.get("CLAUDE_CODE_SESSION_ID"))
    a = ap.parse_args()
    if a.mode == "selftest":
        res = selftest()
    else:
        if not a.successor_map:
            print(json.dumps({"error": "SUCCESSOR_MAP_REQUIRED: pass --successor-map (a stand-in map for PLAN)"}))
            return 2
        CONDITIONAL[:] = a.with_conditional
        v = use_map(a.successor_map)
        if not v["ok"]:
            print(json.dumps({"error": "SUCCESSOR_MAP_INVALID", "checks": v}))
            return 2
        if a.mode == "check" and STATE["stand_in"]:
            print(json.dumps({"error": "STAND_IN_MAP_REFUSED: check runs only on EXECUTE's real map"}))
            return 2
        if a.mode == "registry" and a.emit:
            res = {"record_type": "GCFPE_102726_PLAN_REGISTRY_GUARDS", "stand_in": STATE["stand_in"],
                   "source": "guards.json via body_check.py registry",
                   "assertions": registry_assertions(active_guards(STATE["map"])), "ok": True}
        elif a.mode == "registry":
            if not (a.audit_root and a.session):
                print(json.dumps({"error": "registry needs --audit-root and a session"}))
                return 2
            res = registry(a.audit_root, a.harness_root, a.session, a.since_minutes, a.fetched_after,
                           a.with_conditional)
        else:
            if not a.session:
                print(json.dumps({"error": "SESSION_UNKNOWN: set CLAUDE_CODE_SESSION_ID or --session"}))
                return 2
            res = run(a.mode, a.prompts, a.no_ops, a.harness_root, a.session, a.since_minutes, a.fetched_after,
                      a.with_conditional)
            res["successor_map_checks"] = v
    print(json.dumps(res, indent=1, ensure_ascii=False))
    return 0 if res["ok"] else 1


